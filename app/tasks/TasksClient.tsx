"use client";

import { useEffect, useState, type ReactNode } from "react";
import { DashboardBackLink } from "@/components/navigation/DashboardBackLink";
import { generateTasksFromHighRiskMembers } from "@/lib/taskGenerator";
import { getInterventionSuggestion } from "@/lib/interventionSuggestion";
import { Task, Member } from "@/types";
import { formatTaskActionForDisplay } from "@/lib/taskActionDisplayLabels";

function getStatusColor(status: string): string {
  switch (status) {
    case "pending":
      return "text-yellow-700 bg-yellow-400/10 border-yellow-400/20";
    case "in progress":
      return "text-blue-700 bg-blue-400/10 border-blue-400/20";
    case "done":
      return "text-green-700 bg-green-400/10 border-green-400/20";
    default:
      return "text-slate-600 bg-slate-100 border-slate-200";
  }
}

function getPriorityColor(priority: "low" | "medium" | "high" | undefined): string {
  switch (priority) {
    case "high":
      return "text-red-600 bg-red-400/10 border-red-400/20";
    case "medium":
      return "text-orange-700 bg-orange-400/10 border-orange-400/20";
    case "low":
      return "text-slate-600 bg-slate-100 border-slate-200";
    default:
      return "text-slate-600 bg-slate-100 border-slate-200";
  }
}

function getStatusLabel(status: Task["status"]): string {
  if (status === "pending") return "未対応";
  if (status === "in progress") return "対応中";
  return "完了";
}

function toTwoLineText(text: string, max = 64): string {
  if (text.length <= max) return text;
  return `${text.slice(0, max)}...`;
}

function DetailField({
  label,
  children,
}: {
  label: string;
  children: ReactNode;
}) {
  return (
    <div className="py-3.5 border-b border-slate-100 last:border-b-0">
      <div className="text-xs font-semibold uppercase tracking-wide text-slate-500 mb-1.5">
        {label}
      </div>
      <div className="text-sm text-slate-900 leading-relaxed">{children}</div>
    </div>
  );
}

function ChevronRightIcon({ className }: { className?: string }) {
  return (
    <svg
      className={className}
      width="20"
      height="20"
      viewBox="0 0 20 20"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      aria-hidden
    >
      <path
        d="M7.5 4.5L12.5 10L7.5 15.5"
        stroke="currentColor"
        strokeWidth="1.75"
        strokeLinecap="round"
        strokeLinejoin="round"
      />
    </svg>
  );
}

function taskCreationReason(task: Task, member: Member | undefined): string {
  if (task.isAutoGenerated) {
    if (member) {
      const suggestion = getInterventionSuggestion(member);
      const p =
        suggestion.priority === "high"
          ? "高"
          : suggestion.priority === "medium"
            ? "中"
            : "低";
      return `リスク評価・介入提案（優先度：${p}）に基づき自動生成されています。`;
    }
    return "システムにより自動生成されたタスクです。";
  }
  return "手動で登録されたタスクです。";
}

function mergeServerTasks(fetchedTasks: Task[], members: Member[]): Task[] {
  const autoGeneratedTasks = generateTasksFromHighRiskMembers(members);
  const existingTaskIds = new Set(fetchedTasks.map((t) => t.memberId));
  const newAutoTasks = autoGeneratedTasks.filter(
    (task) => !existingTaskIds.has(task.memberId)
  );
  return [...fetchedTasks, ...newAutoTasks];
}

function buildStatuses(allTasks: Task[]): Record<string, Task["status"]> {
  const initial: Record<string, Task["status"]> = {};
  allTasks.forEach((task) => {
    initial[task.id] = task.status;
  });
  return initial;
}

type Props = {
  initialTasks: Task[];
  initialMembers: Member[];
};

export default function TasksClient({ initialTasks, initialMembers }: Props) {
  const [tasks] = useState<Task[]>(() => mergeServerTasks(initialTasks, initialMembers));
  const [taskStatuses, setTaskStatuses] = useState<Record<string, Task["status"]>>(() =>
    buildStatuses(mergeServerTasks(initialTasks, initialMembers))
  );
  const [isMobile, setIsMobile] = useState(false);
  const [detailTaskId, setDetailTaskId] = useState<string | null>(null);

  console.log("[render-check] app/tasks/TasksClient.tsx rendered");

  const handleStartTask = (taskId: string) => {
    setTaskStatuses((prev) => ({
      ...prev,
      [taskId]: "in progress",
    }));
  };

  const handleMarkAsDone = (taskId: string) => {
    setTaskStatuses((prev) => ({
      ...prev,
      [taskId]: "done",
    }));
  };

  const currentTasks = tasks.map((task) => ({
    ...task,
    status: taskStatuses[task.id] || task.status,
  }));

  const detailTask =
    detailTaskId != null
      ? currentTasks.find((t) => t.id === detailTaskId)
      : undefined;
  const detailMember = detailTask
    ? initialMembers.find((m) => m.id === detailTask.memberId)
    : undefined;

  useEffect(() => {
    const media = window.matchMedia("(max-width: 767px)");
    const sync = () => {
      const mobile = media.matches;
      setIsMobile(mobile);
      if (!mobile) setDetailTaskId(null);
    };
    sync();
    media.addEventListener("change", sync);
    return () => media.removeEventListener("change", sync);
  }, []);

  useEffect(() => {
    if (!isMobile || !detailTaskId) return;
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") setDetailTaskId(null);
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [isMobile, detailTaskId]);

  useEffect(() => {
    if (!isMobile || !detailTaskId) return;
    const prev = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    return () => {
      document.body.style.overflow = prev;
    };
  }, [isMobile, detailTaskId]);

  if (tasks.length === 0) {
    return (
      <div className="container mx-auto px-4 py-8 max-w-7xl">
        <div className="mb-6">
          <DashboardBackLink className="text-blue-700 hover:text-blue-800 hover:underline text-sm">
            ← ダッシュボードに戻る
          </DashboardBackLink>
        </div>
        <h1 className="text-4xl font-bold mb-8">介入タスク</h1>
        <div className="bg-white border border-slate-200 shadow-sm rounded-lg p-8 text-center">
          <p className="text-slate-600">表示するタスクがありません</p>
        </div>
      </div>
    );
  }

  const pendingCount = currentTasks.filter((task) => task.status === "pending").length;
  const inProgressCount = currentTasks.filter((task) => task.status === "in progress").length;
  const doneCount = currentTasks.filter((task) => task.status === "done").length;

  return (
    <div className="container mx-auto px-4 py-8 max-w-7xl">
      <div className="mb-6">
        <DashboardBackLink className="text-blue-700 hover:text-blue-800 hover:underline text-sm">
          ← ダッシュボードに戻る
        </DashboardBackLink>
      </div>
      <h1 className="text-2xl md:text-4xl font-bold mb-4 md:mb-8">タスク一覧</h1>

      <div className="grid grid-cols-1 md:grid-cols-3 gap-6 mb-8">
        <div className="bg-white border border-slate-200 shadow-sm rounded-lg p-6 hover:border-slate-200 transition-colors">
          <h2 className="text-slate-600 text-sm font-medium mb-2">未対応タスク</h2>
          <p className="text-3xl font-bold text-yellow-700">{pendingCount}</p>
        </div>

        <div className="bg-white border border-slate-200 shadow-sm rounded-lg p-6 hover:border-slate-200 transition-colors">
          <h2 className="text-slate-600 text-sm font-medium mb-2">対応中タスク</h2>
          <p className="text-3xl font-bold text-blue-700">{inProgressCount}</p>
        </div>

        <div className="bg-white border border-slate-200 shadow-sm rounded-lg p-6 hover:border-slate-200 transition-colors">
          <h2 className="text-slate-600 text-sm font-medium mb-2">完了タスク</h2>
          <p className="text-3xl font-bold text-green-700">{doneCount}</p>
        </div>
      </div>

      {isMobile ? (
        <>
          <div className="space-y-2">
            {currentTasks.map((task) => {
              const member = initialMembers.find((m) => m.id === task.memberId);
              const storeLabel =
                member?.storeName ||
                (task.storeId ? `店舗ID: ${task.storeId}` : null);
              return (
                <div
                  key={task.id}
                  className="rounded-lg border border-slate-200 bg-white shadow-sm overflow-hidden"
                >
                  <button
                    type="button"
                    onClick={() => setDetailTaskId(task.id)}
                    className="w-full text-left px-3 pt-2.5 pb-2 active:bg-slate-50 hover:bg-slate-50/90 transition-colors focus:outline-none focus-visible:ring-2 focus-visible:ring-blue-500/40 focus-visible:ring-inset"
                  >
                    <div className="flex items-start gap-2">
                      <div className="min-w-0 flex-1">
                        <div className="flex items-center gap-2 flex-wrap">
                          <p className="text-sm font-semibold text-slate-900 leading-snug">
                            {task.memberName}
                          </p>
                          {task.isAutoGenerated && (
                            <span className="shrink-0 text-[10px] px-1.5 py-0.5 rounded bg-blue-500/15 text-blue-800 border border-blue-500/25">
                              自動
                            </span>
                          )}
                        </div>
                        {storeLabel && (
                          <p className="text-[11px] text-slate-500 mt-0.5 truncate">
                            {storeLabel}
                          </p>
                        )}
                      </div>
                      <ChevronRightIcon className="shrink-0 text-slate-400 mt-0.5" />
                    </div>

                    <p className="mt-2 text-[11px] leading-4 text-slate-800 pr-1">
                      <span className="text-slate-500">アクション</span>
                      <span className="line-clamp-2 break-words block mt-0.5">
                        {toTwoLineText(formatTaskActionForDisplay(task.action), 48)}
                      </span>
                    </p>

                    <div className="mt-2 flex flex-wrap items-center gap-2">
                      {task.priority ? (
                        <span
                          className={`inline-flex items-center rounded border px-2 py-0.5 text-[10px] font-medium ${getPriorityColor(
                            task.priority
                          )}`}
                        >
                          {task.priority === "high"
                            ? "高"
                            : task.priority === "medium"
                              ? "中"
                              : "低"}
                        </span>
                      ) : null}
                      <span
                        className={`inline-flex items-center rounded-full border px-2 py-0.5 text-[10px] font-medium ${getStatusColor(
                          task.status
                        )}`}
                      >
                        {getStatusLabel(task.status)}
                      </span>
                      <span className="text-[10px] text-blue-700 font-medium ml-auto">
                        詳細
                      </span>
                    </div>
                  </button>

                  <div className="px-3 pb-2.5 pt-0.5 border-t border-slate-100 flex flex-wrap gap-1.5">
                    {task.status === "pending" && (
                      <button
                        type="button"
                        onClick={() => handleStartTask(task.id)}
                        className="rounded-md px-2.5 py-1.5 text-[11px] bg-blue-500/20 text-blue-800 border border-blue-500/35 hover:bg-blue-500/30 active:scale-[0.98] transition-transform"
                      >
                        タスク開始
                      </button>
                    )}
                    {task.status === "in progress" && (
                      <button
                        type="button"
                        onClick={() => handleMarkAsDone(task.id)}
                        className="rounded-md px-2.5 py-1.5 text-[11px] bg-green-500/20 text-green-800 border border-green-500/35 hover:bg-green-500/30 active:scale-[0.98] transition-transform"
                      >
                        完了にする
                      </button>
                    )}
                    {task.status === "done" && (
                      <span className="px-1 py-1.5 text-[11px] text-slate-500">
                        完了済み
                      </span>
                    )}
                  </div>
                </div>
              );
            })}
          </div>

          {detailTask && (
            <div
              className="fixed inset-0 z-[100] flex flex-col justify-end"
              role="dialog"
              aria-modal="true"
              aria-labelledby="mobile-task-detail-title"
            >
              <button
                type="button"
                className="absolute inset-0 bg-slate-900/45 backdrop-blur-[1px]"
                onClick={() => setDetailTaskId(null)}
                aria-label="閉じる"
              />
              <div className="relative z-[1] mx-auto w-full max-w-lg rounded-t-2xl bg-white shadow-2xl border-t border-slate-200 max-h-[min(88vh,640px)] flex flex-col">
                <div className="shrink-0 px-4 pt-3 pb-3 border-b border-slate-100">
                  <div className="flex justify-center mb-3">
                    <div
                      className="h-1 w-11 rounded-full bg-slate-200"
                      aria-hidden
                    />
                  </div>
                  <div className="flex items-center justify-between gap-3">
                    <h2
                      id="mobile-task-detail-title"
                      className="text-base font-bold text-slate-900"
                    >
                      タスク詳細
                    </h2>
                    <button
                      type="button"
                      onClick={() => setDetailTaskId(null)}
                      className="shrink-0 rounded-lg px-3 py-1.5 text-sm text-slate-600 hover:bg-slate-100 active:bg-slate-200"
                    >
                      閉じる
                    </button>
                  </div>
                </div>
                <div className="overflow-y-auto overscroll-contain px-4 pb-6 pt-1 flex-1 min-h-0">
                  <DetailField label="会員名">{detailTask.memberName}</DetailField>
                  <DetailField label="対象店舗">
                    {detailMember?.storeName ||
                      (detailTask.storeId
                        ? `店舗ID: ${detailTask.storeId}`
                        : "—")}
                  </DetailField>
                  <DetailField label="アクション内容">
                    {formatTaskActionForDisplay(detailTask.action)}
                  </DetailField>
                  <DetailField label="優先度">
                    {detailTask.priority ? (
                      <span
                        className={`inline-flex items-center rounded border px-2.5 py-1 text-xs font-medium ${getPriorityColor(
                          detailTask.priority
                        )}`}
                      >
                        {detailTask.priority === "high"
                          ? "高"
                          : detailTask.priority === "medium"
                            ? "中"
                            : "低"}
                      </span>
                    ) : (
                      "—"
                    )}
                  </DetailField>
                  <DetailField label="ステータス">
                    <span
                      className={`inline-flex items-center rounded-full border px-3 py-1 text-xs font-medium ${getStatusColor(
                        detailTask.status
                      )}`}
                    >
                      {getStatusLabel(detailTask.status)}
                    </span>
                  </DetailField>
                  <DetailField label="担当トレーナー">
                    {detailTask.assignedTrainer || "—"}
                  </DetailField>
                  <DetailField label="期限">{detailTask.dueDate || "—"}</DetailField>
                  <DetailField label="タスクの作成理由">
                    {taskCreationReason(detailTask, detailMember)}
                  </DetailField>
                  <DetailField label="関連メモ（会員）">
                    {detailMember?.notes?.trim()
                      ? detailMember.notes
                      : "会員メモは登録されていません。"}
                  </DetailField>
                  <DetailField label="対応履歴">
                    <span className="text-slate-500">
                      タスク単位の対応履歴は未連携です。
                    </span>
                  </DetailField>

                  <div className="mt-5 pt-2 flex flex-wrap gap-2">
                    {detailTask.status === "pending" && (
                      <button
                        type="button"
                        onClick={() => handleStartTask(detailTask.id)}
                        className="rounded-lg px-4 py-2.5 text-sm font-medium bg-blue-600 text-white hover:bg-blue-700 active:scale-[0.98] transition-transform"
                      >
                        対応開始
                      </button>
                    )}
                    {detailTask.status === "in progress" && (
                      <button
                        type="button"
                        onClick={() => handleMarkAsDone(detailTask.id)}
                        className="rounded-lg px-4 py-2.5 text-sm font-medium bg-green-600 text-white hover:bg-green-700 active:scale-[0.98] transition-transform"
                      >
                        完了にする
                      </button>
                    )}
                    {detailTask.status === "done" && (
                      <p className="text-sm text-slate-500 py-2">このタスクは完了済みです。</p>
                    )}
                  </div>
                </div>
              </div>
            </div>
          )}
        </>
      ) : (
      <div className="bg-white border border-slate-200 shadow-sm rounded-lg overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full">
            <thead className="bg-slate-100 border-b border-slate-200">
              <tr>
                <th className="px-6 py-4 text-left text-sm font-semibold text-slate-700">
                  会員
                </th>
                <th className="px-6 py-4 text-left text-sm font-semibold text-slate-700">
                  アクション
                </th>
                <th className="px-6 py-4 text-left text-sm font-semibold text-slate-700">
                  優先度
                </th>
                <th className="px-6 py-4 text-left text-sm font-semibold text-slate-700">
                  ステータス
                </th>
                <th className="px-6 py-4 text-left text-sm font-semibold text-slate-700">
                  担当トレーナー
                </th>
                <th className="px-6 py-4 text-left text-sm font-semibold text-slate-700">
                  期限
                </th>
                <th className="px-6 py-4 text-left text-sm font-semibold text-slate-700">
                  操作
                </th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-200">
              {currentTasks.map((task) => (
                <tr
                  key={task.id}
                  className="hover:bg-slate-100/80 transition-colors"
                >
                  <td className="px-6 py-4 text-slate-700 font-medium">
                    <div className="flex items-center gap-2">
                      {task.memberName}
                      {task.isAutoGenerated && (
                        <span className="text-xs px-2 py-0.5 rounded bg-blue-500/20 text-blue-700 border border-blue-500/30">
                          自動生成
                        </span>
                      )}
                    </div>
                  </td>
                  <td className="px-6 py-4 text-slate-700">
                    {formatTaskActionForDisplay(task.action)}
                  </td>
                  <td className="px-6 py-4">
                    {task.priority ? (
                      <span
                        className={`inline-flex items-center px-2 py-1 rounded text-xs font-medium border ${getPriorityColor(
                          task.priority
                        )}`}
                      >
                        {task.priority === "high" ? "高" : task.priority === "medium" ? "中" : "低"}
                      </span>
                    ) : (
                      <span className="text-slate-500 text-xs">-</span>
                    )}
                  </td>
                  <td className="px-6 py-4">
                    <span
                      className={`inline-flex items-center px-3 py-1 rounded-full text-xs font-medium border ${getStatusColor(
                        task.status
                      )}`}
                    >
                      {getStatusLabel(task.status)}
                    </span>
                  </td>
                  <td className="px-6 py-4 text-slate-700">
                    {task.assignedTrainer}
                  </td>
                  <td className="px-6 py-4 text-slate-700">{task.dueDate}</td>
                  <td className="px-6 py-4">
                    <div className="flex gap-2">
                      {task.status === "pending" && (
                        <button
                          type="button"
                          onClick={() => handleStartTask(task.id)}
                          className="px-3 py-1.5 text-xs bg-blue-500/20 text-blue-700 border border-blue-500/30 rounded hover:bg-blue-500/30 transition-colors"
                        >
                          タスク開始
                        </button>
                      )}
                      {task.status === "in progress" && (
                        <button
                          type="button"
                          onClick={() => handleMarkAsDone(task.id)}
                          className="px-3 py-1.5 text-xs bg-green-500/20 text-green-700 border border-green-500/30 rounded hover:bg-green-500/30 transition-colors"
                        >
                          完了にする
                        </button>
                      )}
                      {task.status === "done" && (
                        <span className="px-3 py-1.5 text-xs text-slate-500">
                          完了済み
                        </span>
                      )}
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>
      )}
    </div>
  );
}
